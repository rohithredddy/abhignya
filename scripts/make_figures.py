"""Collect paper figures and tables from results/ (aggregate outputs only).

Implements 05_IMPLEMENTATION_ROADMAP Phase 9 and 06_PAPER_OUTLINE ("every number
must come from results/"). Copies PNGs to ``paper/figures/`` and writes booktabs
LaTeX tables to ``paper/tables/``; each table records its source CSV in a comment.

Usage: python scripts/make_figures.py [--results results] [--paper paper]
"""

from __future__ import annotations

import argparse
import json
import shutil
import sys
from pathlib import Path

import numpy as np
import pandas as pd

FIGURES = {
    "E1/fig2_proxy_disagreement.png": "fig2_proxy_disagreement.png",
    "E2/fig3_reliability.png": "fig3_reliability.png",
    "E3/fig4_risk_reduction.png": "fig4_risk_reduction.png",
    "E3/fig5_risk_resamples.png": "fig5_risk_resamples.png",
    "E4/fig6_temporal_shift.png": "fig6_temporal_shift.png",
    "E5/fig7_global_importance.png": "fig7_global_importance.png",
    "E5/fig8_examples.png": "fig8_examples.png",
}


def fmt(v: object, digits: int = 3) -> str:
    if isinstance(v, (float, np.floating)):
        if np.isnan(v):
            return "--"
        if np.isinf(v):
            return r"$-\infty$" if v < 0 else r"$\infty$"
        return f"{v:.{digits}f}"
    return str(v).replace("_", r"\_").replace("%", r"\%")


def latex_table(df: pd.DataFrame, caption: str, label: str, source: str,
                digits: int = 3) -> str:
    cols = "l" * len(df.columns)
    head = " & ".join(fmt(c) for c in df.columns) + r" \\"
    body = "\n".join(" & ".join(fmt(v, digits) for v in row) + r" \\"
                     for row in df.itertuples(index=False))
    return (f"% source: {source} (generated by scripts/make_figures.py; do not edit)\n"
            "\\begin{table}[t]\n\\centering\\scriptsize\n"
            f"\\caption{{{caption}}}\\label{{{label}}}\n"
            f"\\begin{{tabular}}{{{cols}}}\n\\toprule\n{head}\n\\midrule\n{body}\n"
            "\\bottomrule\n\\end{tabular}\n\\end{table}\n")


def with_ci(df: pd.DataFrame, metric: str) -> pd.Series:
    return df.apply(lambda r: f"{r[metric]:.3f} [{r[metric + '_lo']:.3f}, "
                              f"{r[metric + '_hi']:.3f}]", axis=1)


def build_tables(res: Path) -> dict[str, tuple[pd.DataFrame, str, str, str]]:
    """name -> (frame, caption, label, source csv)."""
    out: dict[str, tuple[pd.DataFrame, str, str, str]] = {}
    p = res / "cohort" / "flow.csv"
    if p.exists():
        flow = pd.read_csv(p).pivot(index="step", columns="lab", values="n_events").reset_index()
        out["table1_cohort"] = (flow, "Cohort flow (events per lab).", "tab:cohort", str(p))
    p = res / "E1" / "table2_labels.csv"
    if p.exists():
        t = pd.read_csv(p)[["lab", "n_events", "prev_D", "prev_N", "prev_S", "pct_D_normal",
                            "pct_D_stable"]]
        out["table2_labels"] = (t, "Label prevalence and proxy disagreement.", "tab:labels",
                                str(p))
    p = res / "E2" / "table3_performance.csv"
    if p.exists():
        t = pd.read_csv(p)
        t3 = pd.DataFrame({"lab": t["lab"], "model": t["model"], "AUROC": with_ci(t, "auroc"),
                           "AUPRC": with_ci(t, "auprc"), "Brier": t["brier"], "ECE": t["ece"]})
        out["table3_performance"] = (t3, "Prediction of action change $D$ on test "
                                     "(95\\% patient-level bootstrap CI).", "tab:perf", str(p))
    p = res / "E3" / "table4_certified.csv"
    if p.exists():
        t = pd.read_csv(p)[["lab", "alpha", "risk_test", "resample_risk_mean",
                            "resample_risk_p95", "reduction_test", "resample_reduction_mean",
                            "avoided_per_1000_patient_days"]]
        out["table4_certified"] = (t, "Certified low-value tier: realised risk and reduction "
                                   "vs $\\alpha$.", "tab:crc", str(p))
    p = res / "E4" / "table5_subgroups.csv"
    if p.exists():
        t = pd.read_csv(p)
        main_alpha = 0.01 if 0.01 in set(t["alpha"]) else t["alpha"].min()
        t = t[t["alpha"] == main_alpha].pivot_table(
            index=["lab", "group_var", "group"], columns="method",
            values=["risk", "reduction"]).reset_index()
        t.columns = [" ".join(c).strip() if isinstance(c, tuple) else c for c in t.columns]
        out["table5_subgroups"] = (t, f"Subgroup validity at $\\alpha={main_alpha:g}$: global "
                                   "vs Mondrian CRC.", "tab:subgroups", str(p))
    p = res / "E5" / "table6_faithfulness.csv"
    if p.exists():
        t = pd.read_csv(p)[["lab", "k", "mean_abs_delta_top", "mean_abs_delta_random",
                            "wilcoxon_p"]]
        out["table6_faithfulness"] = (t, "Deletion faithfulness: mean $|\\Delta$EDCP$|$ for "
                                      "top-$k$ vs random-$k$ features.", "tab:faith", str(p))
    p = res / "E6" / "table7_ablations.csv"
    if p.exists():
        t = pd.read_csv(p)
        t = t[(t["alpha"] == 0.01) | t["alpha"].isna()][["lab", "variant", "auroc",
                                                         "resample_risk_mean",
                                                         "resample_reduction_mean", "note"]]
        out["table7_ablations"] = (t.astype(object).fillna(""), "Ablations at $\\alpha=0.01$.",
                                   "tab:abl", str(p))
    return out


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--results", default="results")
    ap.add_argument("--paper", default="paper")
    args = ap.parse_args(argv)
    res, paper = Path(args.results), Path(args.paper)
    (paper / "figures").mkdir(parents=True, exist_ok=True)
    (paper / "tables").mkdir(parents=True, exist_ok=True)
    copied = []
    for src, dst in FIGURES.items():
        if (res / src).exists():
            shutil.copyfile(res / src, paper / "figures" / dst)
            copied.append(dst)
    for name, (df, cap, label, src) in build_tables(res).items():
        (paper / "tables" / f"{name}.tex").write_text(latex_table(df, cap, label, src),
                                                      encoding="utf-8")
        copied.append(f"{name}.tex")
    modes = {json.loads(m.read_text(encoding="utf-8")).get("data_mode")
             for m in res.glob("*/meta.json")}
    (paper / "tables" / "DATA_MODE.txt").write_text(
        f"results data_mode(s): {sorted(m for m in modes if m)}\n"
        "Only data_mode=full results are publishable (demo/synthetic are not).\n",
        encoding="utf-8")
    print(f"wrote {len(copied)} files to {paper}/ (data modes: {sorted(m for m in modes if m)})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
